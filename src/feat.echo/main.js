// ─────────────────────────────────────────────────────────────────────────
// feat.echo —— 回声回复
//
// 它没有界面，只在「发消息」管线的 reply 阶段被调用一次。
// 存在的意义是证明：一个没有 UI 的功能插件可以干干净净地插进同一条链路，
// 而用户侧的发送手感**完全不受它影响**（因为宿主的乐观更新在它之前就完成了）。
//
// 换成真正的模型插件时，把这里换成 nf.fx.http(...) 即可 —— 协议不用变。
// ─────────────────────────────────────────────────────────────────────────
'use strict';

module.exports = {

  onReply: function (e) {
    var text = (e && e.text) || '';

    // 第一条消息给一句自我介绍，之后回声，方便观察链路
    var n = (nf.state.count || 0) + 1;
    nf.state.count = n;

    var reply;
    if (n === 1) {
      reply = '收到：「' + text + '」。这是 feat.echo 插件产生的回复，' +
              '它挂在 message.send 管线的 reply 阶段。';
    } else {
      reply = '（第 ' + n + ' 次回声）' + text;
    }

    return { reply: reply, fx: [] };
  }
};
